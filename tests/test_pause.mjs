import assert from 'node:assert/strict';
import fs from 'node:fs';
import {makeCore,MicroSimulation,newSurvey,recordSurveyAnchor,NODES} from '../sim/engine.mjs';
const core=await makeCore(fs.readFileSync(new URL('../sim/controller.wasm',import.meta.url)));
const survey=newSurvey();for(const n of Object.keys(NODES)) recordSurveyAnchor(survey,n,17);
const sim=new MicroSimulation(core,{mission:['200'],survey,seed:7});
assert.equal(sim.addStop('230'),true);assert.equal(sim.addStop('251'),true);
for(let i=0;i<85;i++)sim.tick(0.08);
const saved=sim.plannedStops();const step=sim.stepIndex;const path=[...sim.plan];
assert.equal(sim.pauseVehicle(),true);
for(let i=0;i<40;i++)sim.tick(0.08);
assert.equal(sim.operatorPaused,true);assert.equal(sim.out[0],0);assert.equal(sim.out[1],0);
assert(Math.abs(sim.robot.lv)<.0001 && Math.abs(sim.robot.rv)<.0001,'motors settle while paused');
assert.deepEqual(sim.plannedStops(),saved);assert.deepEqual(sim.plan,path);assert.equal(sim.stepIndex,step);
assert.equal(sim.mode,'PAUSED');
assert.equal(sim.addStop('263'),true);assert.equal(sim.operatorPaused,true,'add stop does not unpause');
assert.deepEqual(sim.plannedStops(),[...saved,'263']);
sim.wifi=false;for(let i=0;i<16;i++)sim.tick(.08);
assert.equal(sim.resumeVehicle(),false,'refuse resume without connectivity');
assert.equal(sim.out[0],0);assert.equal(sim.out[1],0);
sim.wifi=true;for(let i=0;i<2;i++)sim.tick(.08);
assert.equal(sim.resumeVehicle(),true);
let k=0;while(k++<18000&&!sim.complete&&!sim.failed&&sim.running)sim.tick(.08);
assert.equal(sim.complete,true,'resumed mission should complete');assert.deepEqual(sim.completedStops,['230','251','263']);
assert.equal(sim.pauseVehicle(),false,'cannot pause completed trip');
assert.equal(sim.addStop('200'),true,'subsequent trip still works');
for(let i=0;i<35;i++)sim.tick(.08);
assert.equal(sim.pauseVehicle(),true);
sim.holdAndClear();assert.equal(sim.operatorPaused,false);assert.equal(sim.running,false);assert.equal(sim.plannedStops().length,0);
console.log('Pause/resume integrated test passed; trip visits '+sim.completedStops.join(' -> ')+' and stop clears queue');
